def ensure_classic_quotes(db: Session) -> int:
    """Replace daily quotes with the classic corpus (idempotent by content set)."""
    desired = {(c.strip(), a.strip()) for c, a in CLASSIC_QUOTES if c.strip()}
    existing = db.query(models.DailyQuote).all()
    existing_pairs = {(r.content.strip(), (r.author or "").strip()) for r in existing}

    # If already fully synced, just ensure active flags.
    if desired and desired.issubset(existing_pairs) and len(existing) == len(desired):
        dirty = False
        for r in existing:
            if not r.active:
                r.active = True
                dirty = True
        if dirty:
            db.commit()
        return 0

    # Clear old workbench / incomplete sets, then insert classics.
    for r in existing:
        db.delete(r)
    db.flush()
    for content, author in CLASSIC_QUOTES:
        db.add(models.DailyQuote(content=content, author=author, active=True))
    db.commit()
    return len(CLASSIC_QUOTES)
